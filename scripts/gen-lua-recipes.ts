// Compiles data/recipes.forever.json into the recipe table the addon uses
// to cost a craft offline. The client reports the crafted item and quantity;
// the material list has to come from the dataset, and shipping the whole
// dataset (names, categories, effects) would bloat every login for fields
// the ledger never reads.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { loadRecipeDataset, type DatasetRecipe } from "@/lib/recipes";

const LUA_PATH = fileURLToPath(new URL("../addon/WoWderhoiAH/GeneratedRecipes.lua", import.meta.url));

type Compiled = { mats: Array<[number, number]>; products: Array<[number, number]> };

function compile(recipe: DatasetRecipe): Compiled {
  return {
    mats: recipe.materials
      .filter((material) => material.itemId > 0 && material.qty > 0)
      .map((material) => [material.itemId, material.qty]),
    products: recipe.products
      .filter((product) => product.itemId > 0 && product.qty > 0)
      .map((product) => [product.itemId, product.qty])
  };
}
function pairs(list: Array<[number, number]>): string {
  return `{${list.map(([itemId, qty]) => `{${itemId},${qty}}`).join(",")}}`;
}

export function generateLuaRecipes(): string {
  const dataset = loadRecipeDataset();
  const recipes = dataset.recipes.map((recipe) => ({ id: recipe.id, ...compile(recipe) }));
  // A product produced by several recipes cannot identify a craft on its
  // own; only unique products are registered in the fallback index.
  const productOwners = new Map<number, number[]>();
  for (const recipe of recipes) {
    for (const [itemId] of recipe.products) {
      const owners = productOwners.get(itemId) ?? [];
      owners.push(recipe.id);
      productOwners.set(itemId, owners);
    }
  }
  const productIndex = Array.from(productOwners.entries())
    .filter(([, owners]) => owners.length === 1)
    .map(([itemId, owners]) => `[${itemId}] = ${owners[0]}`);

  // Materials plus the single product id. The product lets the addon check
  // that a recipe id resolved from the client really produces the crafted
  // item before consuming its materials; quantities (crafted and material)
  // still come from the client's own event and the dataset respectively.
  // Recipes whose product the dataset cannot name ship without `p` and stay
  // unverifiable rather than losing their capture.
  const rows = recipes.map((recipe) => {
    const product = recipe.products.length === 1 ? `p=${recipe.products[0][0]},` : "";
    return `[${recipe.id}]={${product}m=${pairs(recipe.mats)}}`;
  });

  return `-- GENERATED by scripts/gen-lua-recipes.ts from data/recipes.forever.json.
-- Do NOT edit by hand: run \`npm run recipes:lua\`. Only the fields the
-- ledger needs are compiled: the material list and the product id.
local ADDON_NAME, WAH = ...

WAH.RECIPES = {
${rows.join(",\n")}
}

-- Product -> recipe, only when exactly one recipe produces that item. A
-- multi-recipe product is ambiguous and the craft capture counts it as
-- unmapped instead of booking the wrong materials.
WAH.RECIPE_BY_PRODUCT = {
  ${productIndex.join(",\n  ")}
}
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const source = generateLuaRecipes();
  writeFileSync(LUA_PATH, source);
  console.log(`Wrote ${LUA_PATH} (${Math.round(source.length / 1024)} KB)`);
}
