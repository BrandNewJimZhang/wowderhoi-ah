// Compiles the single source of truth (src/lib/market-rules.ts) into the
// Lua constants the in-game addon reads. The addon has no build step, so
// the output is committed to the repo; scripts/gen-lua-rules.test.ts fails
// if the committed file drifts from this generator. Regenerate with:
//   npm run gen:lua-rules
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { demandBands } from "@/lib/demand";
import {
  AH_FEE_RATE,
  SCAN_INTERVAL_MINUTES,
  SCAN_PIPELINE_VERSION,
  fillRules,
  marketTypeRules,
  phaseBoundaries,
  phaseHistory,
  portfolioRules,
  sellFrontRules
} from "@/lib/market-rules";

// Core.demandFor reads only the matcher and the weight. levelBand, peakDay
// and note document the prior in src/data; compiling them would ship dead
// data to every client.
const compiledDemand = demandBands.map((band) => ({
  classes: band.classes,
  subClasses: band.subClasses,
  weight: band.weight
}));

// Sizing runs in the shared core: both runtimes allocate one purse across
// the ranked rows, so every knob the allocator reads ships together.
const compiledPortfolio = {
  kellyFraction: portfolioRules.kellyFraction,
  minKellySamples: portfolioRules.minKellySamples,
  maxItemExposure: portfolioRules.maxItemExposure,
  dailyBudget: portfolioRules.dailyBudget
};

const LUA_PATH = fileURLToPath(new URL("../addon/WoWderhoiAH/GeneratedRules.lua", import.meta.url));

function luaTable(value: unknown, indent: string): string {
  if (typeof value === "number" || typeof value === "boolean") return String(value);
  if (typeof value === "string") return JSON.stringify(value);
  if (Array.isArray(value)) return `{ ${value.map((entry) => luaTable(entry, indent)).join(", ")} }`;
  const inner = `${indent}  `;
  const fields = Object.entries(value as Record<string, unknown>).map(
    ([key, entry]) => `${inner}${key} = ${luaTable(entry, inner)}`
  );
  return `{\n${fields.join(",\n")}\n${indent}}`;
}

export function generateLuaRules(): string {
  return `-- GENERATED by scripts/gen-lua-rules.ts from src/lib/market-rules.ts.
-- Do NOT edit by hand: run \`npm run gen:lua-rules\`. The market rules and
-- the pipeline version live in one place (the TS module) so the terminal
-- and the in-game radar can never classify the same scan differently.
local ADDON_NAME, WAH = ...

WAH.PIPELINE_VERSION = ${SCAN_PIPELINE_VERSION}

WAH.RULES = {
  feeRate = ${AH_FEE_RATE},
  scanIntervalMinutes = ${SCAN_INTERVAL_MINUTES},
  sellFront = ${luaTable(sellFrontRules, "")},
  phaseBoundaries = ${luaTable(phaseBoundaries, "")},
  phaseHistory = ${luaTable(phaseHistory, "")},
  fill = ${luaTable(fillRules, "")},
  portfolio = ${luaTable(compiledPortfolio, "")},
  marketTypeRules = ${luaTable(marketTypeRules, "")}
}

WAH.DEMAND = ${luaTable(compiledDemand, "")}
`;
}

// CLI entry: write the file. Guarded so importing the generator (the test)
// does not touch disk.
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(LUA_PATH, generateLuaRules());
  console.log(`Wrote ${LUA_PATH}`);
}
